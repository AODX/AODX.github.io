create or replace function public.eclipse_open_pack(
  p_user uuid,
  p_cost integer,
  p_cards jsonb
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance integer;
  v_item record;
begin
  update public.eclipse_wallets
  set coins = coins - p_cost
  where user_id = p_user and coins >= p_cost
  returning coins into v_balance;

  if v_balance is null then
    raise exception '코인이 부족합니다.';
  end if;

  for v_item in
    select card_id, quantity
    from jsonb_to_recordset(p_cards) as x(card_id text, quantity integer)
  loop
    insert into public.eclipse_collections(user_id, card_id, quantity)
    values (p_user, v_item.card_id, greatest(1, v_item.quantity))
    on conflict (user_id, card_id)
    do update set quantity = public.eclipse_collections.quantity + excluded.quantity, updated_at = now();
  end loop;

  return v_balance;
end;
$$;

create or replace function public.eclipse_commit_match(
  p_room_id uuid,
  p_expected_version integer,
  p_state jsonb,
  p_status text,
  p_winner uuid,
  p_private_states jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_updated integer;
begin
  update public.eclipse_rooms
  set state = p_state,
      status = p_status,
      winner_id = p_winner,
      version = version + 1,
      updated_at = now()
  where id = p_room_id and version = p_expected_version;

  get diagnostics v_updated = row_count;
  if v_updated = 0 then
    return false;
  end if;

  insert into public.eclipse_private_states(room_id, user_id, state)
  select p_room_id, x.user_id, x.state
  from jsonb_to_recordset(p_private_states) as x(user_id uuid, state jsonb)
  on conflict (room_id, user_id)
  do update set state = excluded.state, updated_at = now();

  return true;
end;
$$;

create or replace function public.eclipse_reward_match(
  p_room_id uuid,
  p_user uuid,
  p_coins integer,
  p_xp integer,
  p_won boolean
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inserted integer;
begin
  insert into public.eclipse_match_rewards(room_id, user_id, coins, xp, won)
  values (p_room_id, p_user, p_coins, p_xp, p_won)
  on conflict (room_id, user_id) do nothing;

  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    return false;
  end if;

  insert into public.eclipse_wallets(user_id, coins)
  values (p_user, p_coins)
  on conflict (user_id)
  do update set coins = public.eclipse_wallets.coins + excluded.coins, updated_at = now();

  update public.eclipse_profiles
  set xp = xp + p_xp,
      wins = wins + case when p_won then 1 else 0 end,
      losses = losses + case when p_won then 0 else 1 end
  where user_id = p_user;

  return true;
end;
$$;

