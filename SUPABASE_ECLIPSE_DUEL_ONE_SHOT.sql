create extension if not exists pgcrypto;

create table if not exists public.eclipse_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '신입 결투가',
  player_code text not null unique,
  avatar text not null default 'eclipse',
  status_message text not null default '새로운 덱을 연구하는 중',
  wins integer not null default 0 check (wins >= 0),
  losses integer not null default 0 check (losses >= 0),
  xp integer not null default 0 check (xp >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.eclipse_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  coins integer not null default 500 check (coins >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.eclipse_collections (
  user_id uuid not null references auth.users(id) on delete cascade,
  card_id text not null,
  quantity integer not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, card_id)
);

create table if not exists public.eclipse_decks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null default '기본 덱',
  cards jsonb not null default '[]'::jsonb,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists eclipse_one_active_deck_per_user
on public.eclipse_decks(user_id)
where is_active = true;

create table if not exists public.eclipse_rooms (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  host_id uuid not null references auth.users(id) on delete cascade,
  guest_id uuid references auth.users(id) on delete set null,
  public_match boolean not null default false,
  status text not null default 'waiting' check (status in ('waiting','active','finished','cancelled')),
  ready_host boolean not null default false,
  ready_guest boolean not null default false,
  state jsonb,
  version integer not null default 0,
  winner_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists eclipse_rooms_waiting_idx
on public.eclipse_rooms(public_match, status, created_at)
where guest_id is null;

create table if not exists public.eclipse_private_states (
  room_id uuid not null references public.eclipse_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  state jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create table if not exists public.eclipse_global_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null,
  body text not null check (char_length(body) between 1 and 180),
  created_at timestamptz not null default now()
);

create index if not exists eclipse_global_messages_created_idx
on public.eclipse_global_messages(created_at desc);

create table if not exists public.eclipse_room_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.eclipse_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null,
  body text not null check (char_length(body) between 1 and 180),
  created_at timestamptz not null default now()
);

create index if not exists eclipse_room_messages_room_idx
on public.eclipse_room_messages(room_id, created_at desc);

create table if not exists public.eclipse_friend_requests (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (sender_id <> receiver_id)
);

create unique index if not exists eclipse_pending_friend_pair
on public.eclipse_friend_requests(sender_id, receiver_id)
where status = 'pending';

create table if not exists public.eclipse_friends (
  user_id uuid not null references auth.users(id) on delete cascade,
  friend_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, friend_id),
  check (user_id <> friend_id)
);

create table if not exists public.eclipse_match_rewards (
  room_id uuid not null references public.eclipse_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  coins integer not null,
  xp integer not null,
  won boolean not null,
  created_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create or replace function public.eclipse_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

